  document.querySelectorAll('[data-label-id]').forEach(node => node.setAttribute('aria-label', english ? node.dataset.labelEn : node.dataset.labelId));
  document.querySelector('.lang-opt-id').classList.toggle('active', !english);
  document.querySelector('.lang-opt-en').classList.toggle('active', english);
  document.getElementById('langToggle').setAttribute('aria-label', english ? 'Language: English. Switch to Indonesian' : 'Bahasa: Indonesia. Ganti ke Inggris');
